// Opt-in integration check, intentionally excluded from npm test.
// Usage: node tests/native-plugin-smoke.mjs C:\absolute\path\to\codex.exe
// Generates only a temporary, credential-free home and a no-turn test conversation.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir, mkdtemp, readFile, readdir, realpath, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import readline from 'node:readline';

const executable = process.argv[2];
if (!executable || !path.isAbsolute(executable)) {
  throw new Error('Provide the absolute path to the native codex executable. This test never uses your real Codex home.');
}
const binary = await realpath(executable);
const isolatedHome = await mkdtemp(path.join(os.tmpdir(), 'codex-delete-plugin-smoke-'));
const projectDir = path.join(isolatedHome, 'project');
const sentinelPath = path.join(projectDir, 'keep-this-project-file.txt');
const sentinelContents = 'Project files must survive conversation deletion.\n';
await mkdir(projectDir);
await writeFile(sentinelPath, sentinelContents, 'utf8');

// Credentials, user config overrides, and plugin/tool environment variables are not inherited.
const childEnv = {};
for (const [key, value] of Object.entries(process.env)) {
  if (['SYSTEMROOT', 'WINDIR', 'PATH', 'TEMP', 'TMP', 'PATHEXT', 'COMSPEC'].includes(key.toUpperCase())) {
    childEnv[key] = value;
  }
}
Object.assign(childEnv, {
  CODEX_HOME: isolatedHome, HOME: isolatedHome, USERPROFILE: isolatedHome,
  APPDATA: path.join(isolatedHome, 'AppData', 'Roaming'),
  LOCALAPPDATA: path.join(isolatedHome, 'AppData', 'Local'),
});
const allowedMethods = new Set(['initialize', 'thread/start', 'thread/name/set', 'thread/read', 'thread/list', 'thread/delete']);
const sourceKinds = ['cli', 'vscode', 'exec', 'appServer', 'subAgent', 'subAgentReview',
  'subAgentCompact', 'subAgentThreadSpawn', 'subAgentOther', 'unknown'];
const clients = [];
let createdId;
let report = { passed: false, isolatedHome, projectDir, modelTurnsStarted: 0, realHomeTouched: false };

function createClient(name) {
  const child = spawn(binary, [
    '-c', 'model="probe-model"', '-c', 'model_provider="probe"',
    '-c', 'model_providers.probe={name="Isolated Plugin Smoke",base_url="http://127.0.0.1:1",wire_api="responses"}',
    'app-server', '--stdio',
  ], { cwd: isolatedHome, env: childEnv, windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] });
  const pending = new Map();
  const notifications = [];
  let nextId = 0;
  let stderr = '';
  let stopped;
  const exited = new Promise(resolve => child.once('close', (code, signal) => {
    for (const entry of pending.values()) {
      clearTimeout(entry.timer);
      entry.reject(new Error(`${name} exited before replying (${code ?? signal}).`));
    }
    pending.clear();
    resolve({ code, signal });
  }));
  child.stderr.setEncoding('utf8');
  child.stderr.on('data', text => { stderr += text; });
  const lines = readline.createInterface({ input: child.stdout });
  lines.on('line', text => {
    let message;
    try { message = JSON.parse(text); } catch { return; }
    if (!Object.hasOwn(message, 'id')) { notifications.push(message); return; }
    const entry = pending.get(message.id);
    if (!entry) return;
    pending.delete(message.id);
    clearTimeout(entry.timer);
    if (message.error) entry.reject(Object.assign(new Error(message.error.message), { code: message.error.code }));
    else entry.resolve(message.result);
  });
  child.on('error', error => {
    for (const entry of pending.values()) { clearTimeout(entry.timer); entry.reject(error); }
    pending.clear();
  });
  const client = {
    name, notifications,
    rpc(method, params) {
      assert.ok(allowedMethods.has(method), `Disallowed smoke-test RPC: ${method}`);
      if (['thread/name/set', 'thread/read', 'thread/delete'].includes(method)) {
        assert.match(createdId || '', /^[0-9a-f-]{36}$/i);
        assert.equal(params.threadId, createdId, 'Only the thread generated by this test may be targeted.');
      }
      const id = ++nextId;
      return new Promise((resolve, reject) => {
        const timer = setTimeout(() => {
          pending.delete(id);
          reject(new Error(`Timed out: ${name} ${method}`));
        }, 20000);
        pending.set(id, { resolve, reject, timer });
        child.stdin.write(JSON.stringify({ id, method, params }) + '\n');
      });
    },
    async initialize() {
      const result = await client.rpc('initialize', {
        clientInfo: { name: `codex-delete-plugin-smoke-${name}`, title: 'Isolated Plugin Smoke', version: '1.0.0' },
        capabilities: { experimentalApi: true, requestAttestation: false },
      });
      assert.equal(path.resolve(result.codexHome), path.resolve(isolatedHome));
      child.stdin.write(JSON.stringify({ method: 'initialized', params: {} }) + '\n');
      return result;
    },
    stop() {
      if (stopped) return stopped;
      stopped = (async () => {
        // EOF lets app-server release its runtime and writer lock normally.
        child.stdin.end();
        let forced = false;
        const timer = setTimeout(() => { forced = true; child.kill(); }, 10000);
        const exit = await exited;
        clearTimeout(timer);
        lines.close();
        await writeFile(path.join(isolatedHome, `${name}-stderr.log`), stderr, 'utf8');
        return { ...exit, forced };
      })();
      return stopped;
    },
  };
  clients.push(client);
  return client;
}

async function readThread(client) {
  return (await client.rpc('thread/read', { threadId: createdId, includeTurns: false })).thread;
}

try {
  const a = createClient('A');
  const initA = await a.initialize();
  const b = createClient('B');
  const initB = await b.initialize();
  // Legacy + explicit name durably materializes an empty test thread without a model turn.
  const started = await a.rpc('thread/start', {
    cwd: projectDir, ephemeral: false, environments: [], historyMode: 'legacy',
  });
  createdId = started.thread.id;
  assert.equal(path.resolve(started.thread.cwd), path.resolve(projectDir));
  await a.rpc('thread/name/set', { threadId: createdId, name: 'Disposable isolated plugin smoke thread' });
  const loadedA = await readThread(a);
  const observedB = await readThread(b);
  assert.equal(loadedA.status.type, 'idle');
  assert.equal(observedB.status.type, 'notLoaded');

  let writerConflict;
  await assert.rejects(b.rpc('thread/delete', { threadId: createdId }), error => {
    writerConflict = { code: error.code, message: error.message };
    return error.code === -32600 && /already has an active writer/.test(error.message);
  });
  assert.equal((await readThread(a)).status.type, 'idle', 'Rejected deletion must retain the owning runtime.');
  assert.equal((await readThread(b)).id, createdId, 'Rejected deletion must retain persisted metadata.');

  const exitA = await a.stop();
  assert.equal(exitA.forced, false, 'Owner must exit normally, not be forcibly terminated.');
  assert.equal(exitA.code, 0);
  assert.equal((await readThread(b)).status.type, 'notLoaded');
  await b.rpc('thread/delete', { threadId: createdId });
  let missingRead;
  await assert.rejects(readThread(b), error => {
    missingRead = { code: error.code, message: error.message };
    return error.code === -32600 && /thread not loaded|thread not found|no rollout found/i.test(error.message);
  });
  for (const archived of [false, true]) {
    const page = await b.rpc('thread/list', { archived, modelProviders: [], sourceKinds, limit: 100 });
    assert.ok(!page.data.some(thread => thread.id === createdId));
    assert.ok(!page.nextCursor, 'The fresh isolated home should have no additional pages.');
  }
  assert.ok(b.notifications.some(item => item.method === 'thread/deleted' && item.params.threadId === createdId));
  assert.equal(await readFile(sentinelPath, 'utf8'), sentinelContents);
  assert.deepEqual(await readdir(projectDir), [path.basename(sentinelPath)]);

  report = {
    ...report, passed: true, binary, userAgentA: initA.userAgent, userAgentB: initB.userAgent, createdId,
    beforeOwnerExit: { ownerA: loadedA.status.type, observerB: observedB.status.type },
    crossProcessWriterConflict: writerConflict, ownerExitedNormally: true,
    nativeDeleteAfterOwnerExit: 'passed', readAfterDelete: missingRead,
    absentFromActiveAndArchivedLists: true, deletedNotification: true, projectSentinelUnchanged: true,
  };
} catch (error) {
  report = { ...report, createdId, error: { message: error.message, stack: error.stack } };
  process.exitCode = 1;
} finally {
  const exits = await Promise.allSettled(clients.map(client => client.stop()));
  report.processCleanup = exits.map((entry, index) => ({
    client: clients[index].name,
    ...(entry.status === 'fulfilled' ? entry.value : { error: String(entry.reason) }),
  }));
  const reportPath = path.join(isolatedHome, 'native-plugin-smoke-report.json');
  report.reportPath = reportPath;
  await writeFile(reportPath, JSON.stringify(report, null, 2), 'utf8');
  console.log(JSON.stringify(report, null, 2));
}
